const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const manifest = read('app/src/main/AndroidManifest.xml');
const ui = read('app/src/main/java/app/storylens/phone/MainActivity.java');
const store = read('app/src/main/java/app/storylens/phone/PairingStore.java');
const wire = read('app/src/main/java/app/storylens/phone/HttpsWire.java');
assert.match(manifest, /android:allowBackup="false"/);
assert.match(manifest, /android:usesCleartextTraffic="false"/);
assert.equal((manifest.match(/<uses-permission /g) || []).length, 1);
assert.match(manifest, /android:exported="false" android:grantUriPermissions="true"/);
assert.doesNotMatch(ui, /\bWebView\b|ACTION_VIEW|loadUrl\(|ClipboardManager|Log\./);
assert.match(ui, /ACTION_OPEN_DOCUMENT/);
assert.match(ui, /PICK_CONNECTION/);
assert.match(ui, /out\.size\(\)\+n>4096/);
assert.match(ui, /ACTION_CREATE_DOCUMENT/);
assert.match(ui, /FileProvider\.getUriForFile/);
assert.match(ui, /new VideoView/);
assert.match(ui, /new MediaPlayer/);
assert.match(ui, /new ImageView/);
assert.match(ui, /onStop\(\).*active=false;handler\.removeCallbacks\(poll\);disconnect\(\)/);
assert.match(ui, /putString\("uncertain_chat",chatId\)/);
assert.match(ui, /if\(!local\.edit\(\)[\s\S]*?\.commit\(\)\)\{notice\("Send not started"/);
assert.match(ui, /!uncertain\(\)/);
assert.match(store, /AndroidKeyStore/);
assert.match(store, /AES\/GCM\/NoPadding/);
assert.match(store, /\.setKeySize\(256\)/);
assert.match(store, /putString\("ciphertext",encrypted\)/);
assert.doesNotMatch(store, /putString\("(?:token|key|code)",/);
assert.match(wire, /setInstanceFollowRedirects\(false\)/);
assert.doesNotMatch(wire, /setHostnameVerifier|setSSLSocketFactory/);
assert.match(read('app/src/main/res/xml/file_paths.xml'), /path="received\/"/);
console.log('Native source/manifest contracts passed (not device UI evidence).');
