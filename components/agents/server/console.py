_EMAIL = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")
_PHONE = re.compile(r"(?<!\d)(?:\+?\d{1,3}[ -]?)?\d{5}[ -]?\d{5}(?!\d)")
_SECRET = re.compile(r"\b(?:sk-|xoxb-|ghp_|AIza)[A-Za-z0-9_\-]{8,}")


def demo_mode() -> bool:
    return config.get_bool("DEMO_MODE", False)


def redact(text) -> str:
    """Blank out anything that identifies him or lets you act as him.

    Deliberately blunt. A demo that leaks his inbox once is worse than a demo
    that over-hides, and the shape of the data survives either way - you can
    still see that the agent found a contact address, just not whose.
    """
    s = str(text if text is not None else "")
    if not demo_mode():
        return s
    s = _SECRET.sub("[hidden]", s)
    s = _EMAIL.sub("name@company.example", s)
    s = _PHONE.sub("+91 00000 00000", s)
    return s


def esc(x) -> str:
    return html.escape(redact(x))


