NO_HANDOFF = {"add_target"}


def _digits(value) -> str:
    return re.sub(r"\D+", "", str(value or ""))


def handoff_links(payload: dict) -> list[tuple[str, str]]:
    """Open the message somewhere he can send it himself.

    Approving is what records the decision; these are for the times he would
    rather send it from his own hand - the address and the text are already
    filled in either way, so nothing has to be retyped.

    Hidden in demo mode: a live mailto: with his address in it is exactly
    what demo mode exists to keep off the screen.
    """
    if demo_mode() or str(payload.get("_kind") or "") in NO_HANDOFF:
        return []
    import urllib.parse as _u
    out = []
    subject = str(payload.get("subject") or "")
    body = str(payload.get("body") or "")
    to = str(payload.get("to") or "")
    email = payload.get("best_email") or (to if "@" in to else "")
    if email:
        if config.get_bool("SUITE_STORYLENS_INTEGRATED"):
            q = _u.urlencode({"view": "cm", "fs": "1", "to": email, "su": subject, "body": body})
            out.append(("Open in Gmail", f"https://mail.google.com/mail/?{q}"))
        else:
            q = _u.urlencode({"subject": subject, "body": body}, quote_via=_u.quote)
            out.append(("Open in email", f"mailto:{_u.quote(str(email), safe='@.+_-')}?{q}"))
    phone = _digits(payload.get("best_phone")
                    or (to if "@" not in to else ""))
    if len(phone) >= 10:
        text = str(payload.get("whatsapp_text") or body)
        out.append(("Open in WhatsApp",
                    f"https://wa.me/{phone}?text={_u.quote(text)}"))
    elif str(payload.get("wa_link") or "").startswith("http"):
        out.append(("Open in WhatsApp", str(payload["wa_link"])))
    for key, label in (("contact_form_url", "Open their contact form"),
                       ("apply_url", "Open the application page"),
                       ("url", "Open their site")):
        url = str(payload.get(key) or "")
        if url.startswith("http"):
            out.append((label, url))
            if key != "url":
                break
    return out
