"""The console: what he actually looks at.

The old dashboard was one long page - stats, then everything pending from
every agent in one pile, then two tables. That is fine when you have one
agent. With five it stops answering the only question worth asking, which is
"what does *this* agent want from me, and why does it think that".

So: a rail down the left with the five agents and how many cards each is
holding, and one pane on the right showing that agent and nothing else. Four
things per agent, in the order you would ask about them -

    Waiting      the cards. Approve, edit or reject without leaving the page.
    Learned      the rules it wrote for itself after he rejected something.
    Noticed      what its brain has come to believe, and the evidence for it.
    History      what it did, and what he decided.

There is no build step and no JavaScript framework here on purpose - it is
the same stdlib http.server as everything else, so `python run.py serve` and
a browser is the whole setup. The markup is generated by plain functions that
take rows and return strings, which is also why they are easy to test.

Demo mode (DEMO_MODE=true) is for showing it to somebody. It blanks email
addresses, phone numbers and anything that looks like a key, and refuses
every write - so the page can be put on a screen in an interview without his
inbox being on it.
"""
