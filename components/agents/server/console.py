def preview(a: dict) -> str:
    """The two or three lines that tell you what this card is, at a glance."""
    p = a.get("payload") or {}
    kind = a.get("kind")
    if kind in ("send_email", "send_reply", "interview_reply"):
        head = (p.get("subject") or "").strip()
        body = (p.get("body") or "")[:420]
        to = f"<span class=tag>to {esc(p.get('to'))}</span>" if p.get("to") else ""
        return (f"<div class=meta style='margin-top:6px'>{to}</div>"
                f"<pre>{esc(head)}\n\n{esc(body)}</pre>")
    if kind == "send_quote":
        q = p.get("quote", {}) or {}
        return (f"<div class=meta style='margin-top:6px'>"
                f"<span class='tag money'>{esc(q.get('currency'))} "
                f"{money(q.get('total'))}</span>"
                + (f"<span class=tag>to {esc(p.get('to'))}</span>"
                   if p.get("to") else "")
                + f"</div><pre>{esc(p.get('breakdown', ''))}</pre>")
    if kind == "add_target":
        # "Should this brand go on the list at all?" - a different question
        # from "is this draft good", and it deserves its own shape.
        deal = {"cash": "pays cash", "affiliate": "commission only",
                "barter": "product, not money"}.get(str(p.get("deal_type")), "")
        tags = [t for t in (p.get("segment"), deal, p.get("payout"),
                            f"found on {p.get('source')}" if p.get("source")
                            else "") if t]
        note = str(p.get("note") or "").strip()
        hits = p.get("india_hits") or []
        if isinstance(hits, list) and hits:
            note += ("\n\nWhy it looks Indian: " + ", ".join(str(h)
                                                             for h in hits[:4]))
        return ("<div class=meta style='margin-top:6px'>"
                + "".join(f"<span class=tag>{esc(t)}</span>" for t in tags)
                + "</div>"
                + (f"<pre>{esc(note[:360])}</pre>" if note.strip() else ""))
    if kind == "send_message":
        # A handoff: he sends it himself, from WhatsApp or their form.
        where = {"whatsapp": "WhatsApp", "form": "their contact form",
                 "social": "a DM"}.get(str(p.get("channel")), "by hand")
        text = str(p.get("whatsapp_text") or p.get("body") or "")[:420]
        return (f"<div class=meta style='margin-top:6px'>"
                f"<span class=tag>send over {esc(where)}</span>"
                + (f"<span class=tag>to {esc(p.get('to'))}</span>"
                   if p.get("to") else "")
                + f"</div><pre>{esc(text)}</pre>")
    if kind == "apply_to_job":
        cov = p.get("keyword_coverage", 0) or 0
        return (f"<div class=meta style='margin-top:6px'>"
                f"<span class=tag>{esc(p.get('location'))}</span>"
                + (f"<span class=tag>{esc(p.get('salary'))}</span>"
                   if p.get("salary") else "")
                + f"<span class=tag>resume matches {cov:.0%} of the posting</span>"
                  f"</div><pre>{esc((p.get('description_excerpt') or '')[:320])}</pre>")
    return f"<pre class=code>{esc(json.dumps(p, default=str)[:320])}</pre>"


