@dataclass
class QuoteLine:
    label: str
    days: float
    amount: float


@dataclass
class Quote:
    currency: str
    lines: list = field(default_factory=list)
    subtotal: float = 0.0
    contingency: float = 0.0
    multiplier: float = 1.0
    multipliers_applied: list = field(default_factory=list)
    total: float = 0.0
    total_days: float = 0.0
    retainer_monthly: float = 0.0
    assumptions: list = field(default_factory=list)

    def render(self) -> str:
        cur = self.currency
        out = []
        for l in self.lines:
            out.append(f"  {l.label:<44} {cur} {l.amount:>10,.0f}")
        out.append(f"  {'Subtotal':<44} {cur} {self.subtotal:>10,.0f}")
        if self.contingency:
            out.append(f"  {'Contingency (15%)':<44} {cur} {self.contingency:>10,.0f}")
        for name, factor in self.multipliers_applied:
            pct = (factor - 1) * 100
            label = f"{name.replace('_', ' ').title()} ({pct:+.0f}%)"
            out.append(f"  {label:<44}")
        out.append(f"  {'TOTAL':<44} {cur} {self.total:>10,.0f}")
        if self.retainer_monthly:
            out.append(f"  {'Optional support retainer (monthly)':<44} "
                       f"{cur} {self.retainer_monthly:>10,.0f}")
        return "\n".join(out)

    def to_json(self) -> dict:
        return {
            "currency": self.currency, "total": self.total,
            "total_days": self.total_days, "subtotal": self.subtotal,
            "contingency": self.contingency,
            "multipliers": [list(m) for m in self.multipliers_applied],
            "retainer_monthly": self.retainer_monthly,
            "lines": [{"label": l.label, "days": l.days, "amount": l.amount}
                      for l in self.lines],
            "assumptions": self.assumptions,
        }


    @classmethod
    def from_json(cls, d: dict) -> "Quote":
        """Rebuild a Quote from its checkpointed form after a resume."""
        return cls(
            currency=d.get("currency", "USD"),
            lines=[QuoteLine(l["label"], l.get("days", 0), l.get("amount", 0))
                   for l in d.get("lines", [])],
            subtotal=d.get("subtotal", 0.0),
            contingency=d.get("contingency", 0.0),
            multipliers_applied=[tuple(m) for m in d.get("multipliers", [])],
            total=d.get("total", 0.0), total_days=d.get("total_days", 0.0),
            retainer_monthly=d.get("retainer_monthly", 0.0),
            assumptions=list(d.get("assumptions", [])))


def load_rate_card() -> dict:
    path = config.get("PRICING_FILE",
                      str(config.ROOT / "profiles" / "dev_rate_card.yaml"))
    p = pathlib.Path(path)
    if not p.exists():
        return DEFAULT_RATE_CARD
    try:
        data = load_yaml(p.read_text(encoding="utf-8")) or {}
    except Exception as exc:  # noqa: BLE001
        log.warn(f"could not read rate card {p}: {exc}; using defaults")
        return DEFAULT_RATE_CARD
    merged = {**DEFAULT_RATE_CARD, **data}
    merged["components"] = {**DEFAULT_RATE_CARD["components"],
                            **(data.get("components") or {})}
    merged["multipliers"] = {**DEFAULT_RATE_CARD["multipliers"],
                             **(data.get("multipliers") or {})}
    # The card now carries a day rate per market, because an Indian client will
    # not pay a US day rate and quoting them one loses the domestic work.
    # Flatten the requested market up to the top level, where the quote maths
    # still expects to find it, and keep the floor with it so a negotiation has
    # something to stop at.
    market = (data.get("default_currency") or "usd").lower()
    block = data.get(market) or data.get("usd") or {}
    if block:
        merged["currency"] = block.get("currency", market.upper())
        merged["day_rate"] = block.get("day_rate", merged.get("day_rate"))
        merged["day_rate_floor"] = block.get("day_rate_floor",
                                             merged.get("day_rate", 0) * 0.7)
        merged["minimum_project"] = block.get("minimum_project",
                                              merged.get("minimum_project"))
        merged["contingency"] = block.get("contingency",
                                          merged.get("contingency", 0.15))
    return merged


def rate_card_for(market: str) -> dict:
    """The same card, priced for one market. `market` is "usd" or "inr"."""
    card = dict(load_rate_card())
    raw = card.get("_raw")
    data = raw if isinstance(raw, dict) else None
    if data is None:
        path = pathlib.Path(config.get(
            "PRICING_FILE", str(config.ROOT / "profiles" / "dev_rate_card.yaml")))
        try:
            data = load_yaml(path.read_text(encoding="utf-8")) or {}
        except Exception:  # noqa: BLE001
            return card
    block = data.get((market or "usd").lower()) or {}
    if not block:
        return card
    card["currency"] = block.get("currency", market.upper())
    card["day_rate"] = block.get("day_rate", card.get("day_rate"))
    card["day_rate_floor"] = block.get("day_rate_floor",
                                       float(card.get("day_rate", 0)) * 0.7)
    card["minimum_project"] = block.get("minimum_project",
                                        card.get("minimum_project"))
    return card


def _round_to(value: float, step: int = 50) -> float:
    return float(step * math.ceil(value / step)) if value else 0.0


def build_quote(components: list[str], *, modifiers: list[str] | None = None,
                rate_card: dict | None = None,
                assumptions: list[str] | None = None) -> Quote:
    """Turn a list of scope components into a priced quote. Pure function."""
    card = rate_card or load_rate_card()
    day_rate = float(card.get("day_rate", 320))
    currency = card.get("currency", "USD")
    catalogue = card.get("components", {})

    lines, total_days = [], 0.0
    unknown = []
    for key in components:
        spec = catalogue.get(key)
        if not spec:
            unknown.append(key)
            continue
        days = float(spec.get("days", 0))
        total_days += days
        lines.append(QuoteLine(spec.get("label", key), days,
                               _round_to(days * day_rate)))
    if unknown:
        log.warn(f"unknown scope components ignored: {unknown}")

    subtotal = sum(l.amount for l in lines)
    contingency = _round_to(subtotal * float(card.get("contingency", 0.15)))
    running = subtotal + contingency

    applied, factor = [], 1.0
    for name in (modifiers or []):
        mult = card.get("multipliers", {}).get(name)
        if mult:
            factor *= float(mult)
            applied.append((name, float(mult)))
    total = _round_to(running * factor, 100)
    minimum = float(card.get("minimum_project", 0))
    from core.work_policy import project_floor
    minimum = max(minimum, project_floor(currency))
    notes = list(assumptions or [])
    if total and total < minimum:
        notes.append(f"Raised to the {currency} {minimum:,.0f} project minimum.")
        total = minimum

    retainer = card.get("retainer", {})
    retainer_monthly = _round_to(float(retainer.get("monthly_days", 0)) * day_rate)

    return Quote(currency=currency, lines=lines, subtotal=subtotal,
                 contingency=contingency, multiplier=factor,
                 multipliers_applied=applied, total=total,
                 total_days=total_days, retainer_monthly=retainer_monthly,
                 assumptions=notes)


# --------------------------------------------------------------------------
# scope inference from a prospect's own words
# --------------------------------------------------------------------------
SCOPE_SIGNALS = {
    "marketing_site": [r"\b(landing page|marketing site|brochure site|website "
                       r"redesign|new website|revamp)\b"],
    "web_app_frontend": [r"\b(web app|dashboard|portal|front.?end|react|next\.?js|"
                         r"single page)\b"],
    "backend_api": [r"\b(api|back.?end|database|server|rest|graphql)\b"],
    "microservices": [r"\b(microservice|service.oriented|event.driven|queue|kafka)\b"],
    "auth": [r"\b(login|sign.?up|authentication|sso|user accounts?|roles?)\b"],
    "payments": [r"\b(payment|checkout|stripe|razorpay|billing|subscription)\b"],
    "cms": [r"\b(cms|content management|blog|wordpress|contentful|sanity)\b"],
    "admin_dashboard": [r"\b(admin panel|admin dashboard|back office|internal tool)\b"],
    "migration": [r"\b(migrat|move (off|from)|legacy|port (it|our))\b"],
    "devops": [r"\b(deploy|ci/?cd|hosting|pipeline|docker|kubernetes)\b"],
    "seo_perf": [r"\b(seo|page ?speed|performance|core web vitals|slow)\b"],
}

MODIFIER_SIGNALS = {
    "rush": [r"\b(asap|urgent|rush|by (next )?(week|month)|tight deadline|"
             r"as soon as)\b"],
    "enterprise_compliance": [r"\b(soc ?2|hipaa|gdpr|iso ?27001|compliance|audit|"
                              r"enterprise security)\b"],
    "legacy_integration": [r"\b(legacy|sap|oracle|mainframe|existing erp|"
                           r"tally|on.?prem)\b"],
    "small_business_discount": [r"\b(small business|bootstrap|early stage|"
                                r"tight budget|non.?profit|ngo)\b"],
}


def infer_scope(text: str) -> tuple[list[str], list[str]]:
    """Read a prospect's message and site copy for scope and modifiers."""
    import re
    low = (text or "").lower()
    scope = [key for key, patterns in SCOPE_SIGNALS.items()
             if any(re.search(p, low, re.I) for p in patterns)]
    mods = [key for key, patterns in MODIFIER_SIGNALS.items()
            if any(re.search(p, low, re.I) for p in patterns)]
    return scope, mods
